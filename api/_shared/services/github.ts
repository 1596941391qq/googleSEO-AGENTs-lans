/**
 * 更新README.md，添加新文章摘要
 * 自动提炼文章内容并插入到README中
 */
export async function updateReadmeWithArticleSummary(config: {
  token: string;
  owner: string;
  repoName: string;
  articleSlug: string;
  articleTitle: string;
  articleSummary: string;
  branch?: string;
}): Promise<{ success: boolean; error?: string }> {
  try {
    console.log(`[GitHub updateReadme] Updating README for: ${config.articleTitle}`);

    // 获取当前 README.md
    const response = await fetch(
      `${GITHUB_API_BASE}/repos/${config.owner}/${config.repoName}/contents/README.md?ref=${config.branch || 'main'}`,
      {
        headers: {
          'Authorization': `Bearer ${config.token}`,
          'Accept': 'application/vnd.github.v3+json',
        },
      }
    );

    let currentContent = '';
    let isNewReadme = false;

    if (response.ok) {
      const data = await response.json();
      currentContent = Buffer.from(data.content, 'base64').toString('utf-8');
    } else if (response.status === 404) {
      // README 不存在，创建新的
      console.log(`[GitHub updateReadme] README not found, creating new one`);
      isNewReadme = true;
      currentContent = generateInitialReadme(config.owner, config.repoName);
    } else {
      console.warn(`[GitHub updateReadme] Could not fetch README: ${response.status}`);
      return { success: false, error: `Failed to fetch README: ${response.status}` };
    }

    // 检查文章是否已在 README 中
    if (currentContent.includes(`[${config.articleTitle}]`) || currentContent.includes(config.articleSlug)) {
      console.log(`[GitHub updateReadme] Article already in README, skipping`);
      return { success: true };
    }

    // 生成新的文章条目
    const articleEntry = generateArticleEntry(config.articleSlug, config.articleTitle, config.articleSummary);

    // 插入到 README 中
    let updatedContent = insertArticleIntoReadme(currentContent, articleEntry, isNewReadme);

    // 更新 README.md
    const updateResult = await createOrUpdateFile({
      token: config.token,
      owner: config.owner,
      repoName: config.repoName,
      path: 'README.md',
      content: updatedContent,
      message: `docs: Add "${config.articleTitle}" to README`,
      branch: config.branch,
    });

    if (updateResult.success) {
      console.log(`[GitHub updateReadme] ✅ README updated successfully`);
      return { success: true };
    } else {
      console.error(`[GitHub updateReadme] ❌ Failed to update README: ${updateResult.error}`);
      return { success: false, error: updateResult.error };
    }
  } catch (error: any) {
    console.error('[GitHub updateReadme] Error:', error.message);
    return { success: false, error: error.message };
  }
}

/**
 * 生成初始 README 模板
 */
function generateInitialReadme(owner: string, repoName: string): string {
  return `# ${repoName}

Welcome to the ${repoName} knowledge base.

## 📚 Articles

<!-- Articles will be automatically added below -->

---

*This repository is automatically maintained by NicheDigger PSEO.*
`;
}

/**
 * 生成文章条目
 */
function generateArticleEntry(slug: string, title: string, summary: string): string {
  const date = new Date().toISOString().split('T')[0]; // YYYY-MM-DD
  return `
### [${title}](docs/${slug}.md)

*Published: ${date}*

${summary}

---
`;
}

/**
 * 将文章条目插入到 README 中
 */
function insertArticleIntoReadme(currentContent: string, articleEntry: string, isNewReadme: boolean): string {
  if (isNewReadme) {
    // 新 README，直接追加
    return currentContent.replace(
      '<!-- Articles will be automatically added below -->',
      `<!-- Articles will be automatically added below -->\n${articleEntry}`
    );
  }

  // 查找插入位置
  const marker = '<!-- Articles will be automatically added below -->';
  if (currentContent.includes(marker)) {
    return currentContent.replace(marker, `${marker}\n${articleEntry}`);
  }

  // 如果没有标记，尝试在 "## 📚 Articles" 或 "## Articles" 后面插入
  const articlesHeaderPattern = /## (📚 )?Articles\s*\n/;
  if (articlesHeaderPattern.test(currentContent)) {
    return currentContent.replace(
      articlesHeaderPattern,
      (match) => `${match}\n${articleEntry}`
    );
  }

  // 如果都没有，追加到文件末尾
  return currentContent.trimEnd() + `\n\n## 📚 Articles\n${articleEntry}`;
}

/**
 * 更新旧站点的 MkDocs 配置
 * 将 use_directory_urls: true 改为 false，并添加首页
 */
export async function updateMkDocsConfig(config: {
  token: string;
  owner: string;
  repoName: string;
  siteName: string;
  siteDescription: string;
  branch?: string;
}): Promise<{
  success: boolean;
  changes?: string[];
  error?: string;
}> {
  try {
    console.log(`[GitHub updateMkDocsConfig] Updating config for: ${config.repoName}`);
    const changes: string[] = [];

    // 1. 获取当前 mkdocs.yml
    const response = await fetch(
      `${GITHUB_API_BASE}/repos/${config.owner}/${config.repoName}/contents/mkdocs.yml?ref=${config.branch || 'main'}`,
      {
        headers: {
          'Authorization': `Bearer ${config.token}`,
          'Accept': 'application/vnd.github.v3+json',
        },
      }
    );

    if (!response.ok) {
      return {
        success: false,
        error: `Failed to fetch mkdocs.yml: ${response.status}`,
      };
    }

    const data = await response.json();
    let currentContent = Buffer.from(data.content, 'base64').toString('utf-8');

    // 2. 修改 use_directory_urls: true -> false
    if (currentContent.includes('use_directory_urls: true')) {
      currentContent = currentContent.replace(
        /use_directory_urls: true/g,
        'use_directory_urls: false'
      );
      changes.push('Changed use_directory_urls from true to false');
    }

    // 3. 移除 index_file 配置（如果存在）
    if (currentContent.includes('index_file:')) {
      currentContent = currentContent.replace(/\nindex_file: .+\.md/g, '');
      changes.push('Removed index_file workaround');
    }

    // 4. 添加首页到导航（如果不存在）
    if (!currentContent.includes('- "Home": index.md')) {
      currentContent = currentContent.replace(
        /nav:\n/,
        'nav:\n  - "Home": index.md\n'
      );
      changes.push('Added Home to navigation');
    }

    // 5. 更新 mkdocs.yml
    if (changes.length > 0) {
      const updateResult = await createOrUpdateFile({
        token: config.token,
        owner: config.owner,
        repoName: config.repoName,
        path: 'mkdocs.yml',
        content: currentContent,
        message: 'Update MkDocs config: use flat HTML structure',
        branch: config.branch,
      });

      if (!updateResult.success) {
        return {
          success: false,
          error: `Failed to update mkdocs.yml: ${updateResult.error}`,
        };
      }
    }

    // 6. 创建 docs/index.md（如果不存在）
    const indexMd = `# Welcome to ${config.siteName}

${config.siteDescription}

## Latest Articles

This site is powered by [NicheDigger PSEO](https://nichedigger.ai) - an AI-powered automated search traffic infrastructure platform.

---

*Articles will be automatically listed here as they are published.*
`;

    const indexResult = await createOrUpdateFile({
      token: config.token,
      owner: config.owner,
      repoName: config.repoName,
      path: 'docs/index.md',
      content: indexMd,
      message: 'Add homepage for MkDocs site',
      branch: config.branch,
    });

    if (indexResult.success) {
      changes.push('Created docs/index.md homepage');
    }

    console.log(`[GitHub updateMkDocsConfig] ✅ Config updated successfully`);
    return {
      success: true,
      changes,
    };
  } catch (error: any) {
    console.error('[GitHub updateMkDocsConfig] Error:', error.message);
    return {
      success: false,
      error: error.message,
    };
  }
}
